/** Rebuild the offline India gazetteer from a checksum-pinned CC BY 4.0 source. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = '1.1.65';
const integrity = 'V3BR0kpwFG0OA5Pvsc5sF1/ENtKyweeFIDhyRIoF8p7UTZWxbfiyHXzpy/v0TxYZOHgD4ykXGWVHqUt56IwDFg==';
const archive = process.argv[2];
if (!archive) throw new Error('Usage: node scripts/generate-india-places.mjs /path/to/cities.json-1.1.65.tgz');
const bytes = await readFile(archive);
if (createHash('sha512').update(bytes).digest('base64') !== integrity) throw new Error('Source archive checksum mismatch. Use the exact pinned cities.json version; do not bypass verification.');
const member = name => execFileSync('tar', ['-xOzf', resolve(archive), `package/${name}`], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
const source = JSON.parse(member('cities.json'));
const admin1 = new Map(JSON.parse(member('admin1.json')).map(row => [row.code, row.name]));
const admin2 = new Map(JSON.parse(member('admin2.json')).map(row => [row.code, row.name]));
const regions = [...admin1].filter(([code]) => code.startsWith('IN.')).map(([, name]) => name === 'Andaman and Nicobar' ? 'Andaman and Nicobar Islands' : name).sort();
if (regions.length !== 36) throw new Error('Expected all 36 current Indian states and union territories.');
const selected = source.filter(row => row.country === 'IN');
const districts = [...new Set(selected.map(row => admin2.get(`IN.${row.admin1}.${row.admin2}`) || ''))].sort();
const identities = new Set();
const rows = selected.map(row => {
  const regionName = admin1.get(`IN.${row.admin1}`);
  const region = regions.indexOf(regionName === 'Andaman and Nicobar' ? 'Andaman and Nicobar Islands' : regionName);
  const district = districts.indexOf(admin2.get(`IN.${row.admin1}.${row.admin2}`) || '');
  const lat = Number(row.lat), lon = Number(row.lng);
  if (typeof row.name !== 'string' || !row.name.trim() || region < 0 || !Number.isFinite(lat) || !Number.isFinite(lon) || lat < 6 || lat > 38 || lon < 68 || lon > 98) throw new Error(`Invalid Indian place: ${JSON.stringify(row)}`);
  const identity = `${row.name}|${row.admin1}|${row.admin2}|${row.lat}|${row.lng}`;
  const id = `in-${createHash('sha256').update(identity).digest('hex').slice(0, 14)}`;
  if (identities.has(id)) throw new Error(`Duplicate source identity: ${identity}`);
  identities.add(id);
  return [id, row.name, region, district, lat, lon];
}).sort((a, b) => a[1].localeCompare(b[1], 'en', { sensitivity: 'base' }) || a[0].localeCompare(b[0]));
const seenRegions = new Set(rows.map(row => row[2]));
if (seenRegions.size !== 36 || rows.length !== 7073) throw new Error('The pinned source coverage changed unexpectedly.');
const heading = `/*! India place data adapted from GeoNames, https://www.geonames.org/, via cities.json@${version} (lutangar), https://github.com/lutangar/cities.json. CC BY 4.0: https://creativecommons.org/licenses/by/4.0/. Filtered to India, region/district labels joined, numeric coordinates and deterministic application IDs added. See docs/india-places.md. */\n`;
const output = `${heading}// Generated by scripts/generate-india-places.mjs; do not edit individual rows.\nexport const indiaRegionNames = ${JSON.stringify(regions)};\nexport const indiaDistrictNames = ${JSON.stringify(districts)};\n// [application ID, place name, region index, district index, latitude, longitude]\nexport const indiaPlaceRows = [\n${rows.map(row => JSON.stringify(row)).join(',\n')}\n];\nexport const indiaSourceVersion = ${JSON.stringify(version)};\n`;
await writeFile(resolve(root, 'public/chart-india-data.js'), output);
await mkdir(resolve(root, 'docs/licenses'), { recursive: true });
await writeFile(resolve(root, 'docs/licenses/india-places-CC-BY-4.0.txt'), member('LICENSE'));
console.log(`Generated ${rows.length} India places across ${seenRegions.size} regions (${Math.ceil(Buffer.byteLength(output) / 1024)} KiB).`);
